BEGIN;
DO $$
DECLARE f uuid; other uuid; a uuid; b uuid; target uuid; sibling uuid; report jsonb; owner uuid;
BEGIN
 INSERT INTO driftread.feeds(title,url,category) VALUES('Cleanup A','https://cleanup-a.invalid/rss','Cleanup') RETURNING id INTO f;
 INSERT INTO driftread.feeds(title,url,category) VALUES('Cleanup B','https://cleanup-b.invalid/rss','Cleanup') RETURNING id INTO other;
 INSERT INTO driftread.articles(feed_id,title,url,content,content_hash) VALUES(f,'A repeated article','https://cleanup.invalid/post',repeat('x',150),repeat('a',64)) RETURNING id INTO a;
 INSERT INTO driftread.articles(feed_id,title,url,content,content_hash) VALUES(other,'A repeated article','https://cleanup.invalid/post#part',repeat('x',150),repeat('a',64)) RETURNING id INTO b;
 SELECT id INTO owner FROM auth.users LIMIT 1;
 INSERT INTO driftread.user_bookmarks(user_id,article_id,bookmark_type) VALUES(owner,a,'favorite');
 INSERT INTO driftread.user_feeds(user_id,feed_id) VALUES(owner,f);
 report:=driftread.list_cleanup_items('feeds','category','active','Cleanup',50,0);
 ASSERT (report->>'total')::int=2, 'feed category grouping missing';
 report:=driftread.list_cleanup_items('articles','category','active','Cleanup',50,0);
 ASSERT (report->>'total')::int=2, 'article topic grouping missing';
 report:=driftread.list_cleanup_items('articles','url','active','',50,0);
 ASSERT (SELECT count(*) FROM jsonb_array_elements(report->'items') x WHERE x->>'id' IN (a::text,b::text))=2, 'canonical URL evidence missing';
 report:=driftread.apply_cleanup_batch('articles',ARRAY[a],'stage');
 ASSERT report->>'dry_run'='true';
 ASSERT EXISTS(SELECT 1 FROM driftread.article_publications WHERE id=a), 'preview mutated publication';
 report:=driftread.apply_cleanup_batch('articles',ARRAY[a],'stage',false);
 ASSERT NOT EXISTS(SELECT 1 FROM driftread.article_publications WHERE id=a), 'staged article visible';
 ASSERT EXISTS(SELECT 1 FROM driftread.user_bookmarks WHERE article_id=a), 'stage removed user data';
 report:=driftread.apply_cleanup_batch('articles',ARRAY[a],'restore',false);
 ASSERT EXISTS(SELECT 1 FROM driftread.article_publications WHERE id=a), 'restore changed identity';
 report:=driftread.apply_cleanup_batch('articles',ARRAY[a],'delete',false,true);
 ASSERT report->'items'->0->>'error'='stage_first';
 report:=driftread.apply_cleanup_batch('articles',ARRAY[a],'stage',false);
 report:=driftread.apply_cleanup_batch('articles',ARRAY[a],'delete');
 ASSERT (report->'items'->0->'impact'->>'bookmarks')::int=1, 'missing impact';
 ASSERT EXISTS(SELECT 1 FROM driftread.articles WHERE id=a), 'delete preview mutated article';
 report:=driftread.apply_cleanup_batch('articles',ARRAY[a],'delete',false,true);
 ASSERT NOT EXISTS(SELECT 1 FROM driftread.articles WHERE id=a);
 ASSERT NOT EXISTS(SELECT 1 FROM driftread.article_revisions WHERE article_id=a);
 ASSERT NOT EXISTS(SELECT 1 FROM driftread.user_bookmarks WHERE article_id=a);
 ASSERT EXISTS(SELECT 1 FROM driftread.articles WHERE id=b), 'unselected duplicate removed';
 ASSERT (SELECT article_count FROM driftread.feeds WHERE id=f)=0, 'count cache stale';
 PERFORM driftread.ingest_article_batch(f,jsonb_build_array(jsonb_build_object('title','Again','url','https://cleanup.invalid/post','content','again','content_hash',repeat('b',64))));
 ASSERT NOT EXISTS(SELECT 1 FROM driftread.articles WHERE feed_id=f), 'deleted article resurrected';
 report:=driftread.apply_cleanup_batch('feeds',ARRAY[f],'stage',false);
 ASSERT (SELECT archived_at IS NOT NULL FROM driftread.feeds WHERE id=f);
 report:=driftread.apply_cleanup_batch('feeds',ARRAY[f],'restore',false);
 ASSERT (SELECT archived_at IS NULL FROM driftread.feeds WHERE id=f);
 INSERT INTO driftread.discovery_targets(url,host) VALUES('https://cleanup-target.invalid/','cleanup-target.invalid') RETURNING id INTO target;
 INSERT INTO driftread.discovery_targets(url,host) VALUES('https://cleanup-target.invalid/rss','cleanup-target.invalid') RETURNING id INTO sibling;
 report:=driftread.remove_discovery_targets(ARRAY[target]);
 ASSERT report->'items'->0->>'ok'='true';
 UPDATE driftread.discovery_targets SET status='pending' WHERE id=target;
 ASSERT (SELECT status FROM driftread.discovery_targets WHERE id=target)='removed', 'late worker resurrected target';
 INSERT INTO driftread.discovery_candidates(target_id,feed_url) VALUES(target,'https://cleanup-target.invalid/feed');
 ASSERT NOT EXISTS(SELECT 1 FROM driftread.discovery_candidates WHERE target_id=target), 'cancelled probe created candidate';
 ASSERT (SELECT status FROM driftread.discovery_targets WHERE id=sibling)='pending', 'sibling URL blocked';
 report:=driftread.remove_discovery_targets(ARRAY[target,gen_random_uuid()]);
 ASSERT jsonb_array_length(report->'items')=2;
 INSERT INTO driftread.user_feeds(user_id,feed_id) VALUES(owner,other);
 INSERT INTO driftread.user_bookmarks(user_id,article_id,bookmark_type) VALUES(owner,b,'favorite');
 report:=driftread.apply_cleanup_batch('feeds',ARRAY[other],'stage',false);
 report:=driftread.apply_cleanup_batch('feeds',ARRAY[other],'delete');
 ASSERT (report->'items'->0->'impact'->>'subscriptions')::int=1;
 ASSERT (report->'items'->0->'impact'->>'bookmarks')::int=1;
 report:=driftread.apply_cleanup_batch('feeds',ARRAY[other],'delete',false,true);
 ASSERT NOT EXISTS(SELECT 1 FROM driftread.feeds WHERE id=other);
 ASSERT NOT EXISTS(SELECT 1 FROM driftread.articles WHERE id=b);
 ASSERT NOT EXISTS(SELECT 1 FROM driftread.user_feeds WHERE feed_id=other);
 ASSERT EXISTS(SELECT 1 FROM driftread.feeds WHERE id=f), 'unselected feed deleted';
 UPDATE driftread.discovery_targets SET status='rejected' WHERE id=target;
 ASSERT (SELECT status FROM driftread.discovery_targets WHERE id=target)='rejected', 'explicit host block was ignored';
 INSERT INTO driftread.discovery_candidates(target_id,feed_url) VALUES(target,'https://cleanup-target.invalid/blocked-rss');
 ASSERT NOT EXISTS(SELECT 1 FROM driftread.discovery_candidates WHERE target_id=target), 'blocked probe created candidate';
END $$;
ROLLBACK;
